export type RouteGeometry = {
  viewBox: string;
  arc: string;
  origin: { x: number; y: number; px: number; py: number };
  destination: { x: number; y: number; px: number; py: number };
  dotRadius: number;
};

/**
 * A curved route between two ports, framed to fill a box of the given aspect ratio (width / height).
 * Returns null when a port has no coordinates. px/py are percentages for placing HTML labels.
 */
export function routeGeometry(originCode: string, destinationCode: string, aspect: number): RouteGeometry | null {
  const o = PORT_COORDS[originCode];
  const d = PORT_COORDS[destinationCode];
  if (!o || !d) return null;
  let ox = o[0];
  let dx = d[0];
  if (dx - ox > 180) ox += 360;
  else if (ox - dx > 180) dx += 360;
  const oy = -o[1];
  const dy = -d[1];
  const len = Math.hypot(dx - ox, dy - oy) || 1;
  let nx = -(dy - oy) / len;
  let ny = (dx - ox) / len;
  if (ny > 0) {
    nx = -nx;
    ny = -ny;
  }
  const cx = (ox + dx) / 2 + nx * len * 0.22;
  const cy = (oy + dy) / 2 + ny * len * 0.22;

  let minX = Math.min(ox, dx, cx);
  let maxX = Math.max(ox, dx, cx);
  let minY = Math.min(oy, dy, cy);
  let maxY = Math.max(oy, dy, cy);
  const padX = (maxX - minX) * 0.2 + 6;
  const padY = (maxY - minY) * 0.3 + 6;
  minX -= padX;
  maxX += padX;
  minY -= padY;
  maxY += padY;
  let w = maxX - minX;
  let h = maxY - minY;
  if (w / h < aspect) {
    const nw = h * aspect;
    minX -= (nw - w) / 2;
    w = nw;
  } else {
    const nh = w / aspect;
    minY -= (nh - h) / 2;
    h = nh;
  }
  const pct = (x: number, y: number) => ({ x, y, px: ((x - minX) / w) * 100, py: ((y - minY) / h) * 100 });
  const f = (n: number) => n.toFixed(2);
  return {
    viewBox: `${f(minX)} ${f(minY)} ${f(w)} ${f(h)}`,
    arc: `M${f(ox)} ${f(oy)} Q${f(cx)} ${f(cy)} ${f(dx)} ${f(dy)}`,
    origin: pct(ox, oy),
    destination: pct(dx, dy),
    dotRadius: w / 72,
  };
}
